

class Movie {
  final String id;
  final String name;
  final String venue;
  final String synopsis;
  final String ageRating;
  final String screeningTime;
  final String price;
  
  const Movie({
    required this.id,
    required this.name,
    required this.venue,
    required this.synopsis,
    required this.ageRating,
    required this.screeningTime,
    required this.price,
  });
}